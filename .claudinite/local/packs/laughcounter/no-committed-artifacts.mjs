// "Don't prune a `.gitignore` section in the same breath as deleting what it
// ignored" as a check: no build or tooling artifact is in the repo's file set.
//
// The prose it stands beside describes the accident, not a villain. Removing a
// toolchain (this repo did remove a whole Python reference) invites tidying its
// ignore rules away in the same commit — and the artifacts that toolchain already
// produced are usually still sitting in the worktree. The moment the ignore rules
// go, `git add -A` sweeps them *into* the commit that was supposed to remove
// them, and nothing complains: the commit is valid, the tests still pass, and the
// junk shows up only as an inflated file count in the diff a reviewer reads.
//
// Why a check can see this at all: `ctx.files` is tracked files plus untracked
// files git does *not* ignore. So both halves of the accident are visible, and
// the earlier one is visible first — the instant an ignore rule is deleted while
// its artifacts sit in the worktree, those artifacts stop being ignored and enter
// the file set, before any commit exists. The check does not need to read a byte:
// the path is the whole signal.
//
// A denylist, deliberately — and RULES.md's "write a check as a positive
// whitelist over an enumerated API surface" is what says so. That rule ends "only
// invert this where the allowed set is genuinely open-ended", and here it is: the
// allowed set is *every source file anyone will ever add*. What is enumerable is
// the other side — the artifact shapes, taken from this repo's own `.gitignore`
// (`build/`, `dist/`, `.DS_Store`, `*.xcuserstate`, `.swiftpm/`) plus the
// toolchains this tree has hosted: SwiftPM/Xcode (`.build/`, `DerivedData/`,
// `*.o`, `*.dSYM/`, `.app/` bundles), the departed Python reference
// (`__pycache__/`, `*.pyc`), the macOS packaging output (`*.dmg`), and Node.
//
// Matching is on whole path *segments*, never substrings. This repo ships
// `mac/scripts/build-app.sh` and a `dev/` tree full of build prose; a check that
// flagged "build" anywhere in a path would cry wolf on the first file a reader
// looks at. A fixture pins that distinction.
//
// Dependency-free by design (a local pack must load without the canon mount),
// so the finding object is built by hand rather than via the engine helper.

// A path segment that IS the artifact: a directory (or bundle) that only ever
// holds generated output.
const ARTIFACT_DIRS = new Set([
  'build',
  'dist',
  '.build',
  'DerivedData',
  'node_modules',
  '__pycache__',
  '.pytest_cache',
  '.mypy_cache',
  '.ruff_cache',
  '.swiftpm',
]);

// A segment whose *suffix* makes it an artifact directory or bundle.
const ARTIFACT_DIR_SUFFIXES = ['.app', '.dSYM', '.egg-info', '.xcuserdatad'];

// A file that is itself generated output.
const ARTIFACT_FILES = new Set(['.DS_Store']);
const ARTIFACT_FILE_SUFFIXES = ['.pyc', '.pyo', '.o', '.xcuserstate', '.dmg'];

const endsWithAny = (name, suffixes) => suffixes.some((s) => name.endsWith(s));

// Returns what makes this path an artifact, or null. Segment-wise, so
// `mac/scripts/build-app.sh` and `Builder.swift` are not `build/`.
function artifactReason(path) {
  const segments = path.split('/');
  const name = segments[segments.length - 1];
  for (const segment of segments.slice(0, -1)) {
    if (ARTIFACT_DIRS.has(segment)) return `it lives under a \`${segment}/\` directory`;
    if (endsWithAny(segment, ARTIFACT_DIR_SUFFIXES)) return `it lives inside the \`${segment}\` bundle`;
  }
  if (ARTIFACT_DIRS.has(name)) return `\`${name}\` is a build directory`;
  if (endsWithAny(name, ARTIFACT_DIR_SUFFIXES)) return `\`${name}\` is a build bundle`;
  if (ARTIFACT_FILES.has(name)) return `\`${name}\` is generated by macOS, never by a human`;
  if (endsWithAny(name, ARTIFACT_FILE_SUFFIXES)) return `\`${name}\` is build output`;
  return null;
}

const rule = {
  id: 'laughcounter/no-committed-artifacts',
  severity: 'blocking',
  description: 'No build or tooling artifact in the repo file set (build output, caches, editor state)',
  doc: '.claudinite/local/packs/laughcounter/RULES.md',
  why: "an artifact swept in by a bulk `git add -A` breaks nothing — the commit is valid and the tests pass — so it survives review as an inflated file count nobody reads, and it usually arrives in the very commit that deleted the ignore rule covering it",

  run(ctx) {
    const out = [];
    for (const file of ctx.files) {
      const reason = artifactReason(file);
      if (reason === null) continue;
      out.push({
        rule: rule.id,
        severity: rule.severity,
        file,
        line: null,
        what: `\`${file}\` is a build artifact, not source — ${reason}`,
        why: rule.why,
        fix: "delete it from the worktree (or `git clean` it) and restore the `.gitignore` line that covered it — when you remove a toolchain, clear its artifacts *before* dropping its ignore rules, never in the same breath; if it is already committed, `git rm --cached` it. After any bulk `git add -A`, read `git diff --cached --stat`, not just `git status` — staged additions are exactly what a clean `git status` stops telling you about",
        doc: rule.doc,
      });
    }
    return out;
  },
};

export default rule;
